// Builds src/assets/icons.css: a local stylesheet covering exactly the icons
// this site uses, so nothing is fetched from an icon CDN at runtime.
//
// index.html used to pull two third-party stylesheets — Boxicons from unpkg and
// Unicons from iconscout — into the critical path. That is ~136 kB of CSS plus
// two webfonts, from two origins with no subresource integrity, to draw about
// forty glyphs. An outage or a tampered file at either host took the site's
// icons with it.
//
// The class names are unchanged (`<i className="bx bx-award" />` still works),
// so no component had to be touched. Each icon becomes a CSS mask over
// `currentColor`, which keeps the two things the font gave us: `color` tints
// the icon, and `font-size` scales it, because the box is sized in `em`.
//
// Run with `npm run icons` after adding an icon to a component. The output is
// committed, so builds and fresh clones never need the network.

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { extname, join } from 'node:path';

const SOURCE_DIR = join(process.cwd(), 'src');
const OUTPUT = join(SOURCE_DIR, 'assets', 'icons.css');

const BOXICONS_VERSION = '2.1.4';
const UNICONS_VERSION = '4.0.8';

// Where each family's individual SVGs live on unpkg.
const sourceUrl = (name) => {
  if (name.startsWith('bxl-')) {
    return `https://unpkg.com/boxicons@${BOXICONS_VERSION}/svg/logos/${name}.svg`;
  }
  if (name.startsWith('bxs-')) {
    return `https://unpkg.com/boxicons@${BOXICONS_VERSION}/svg/solid/${name}.svg`;
  }
  if (name.startsWith('bx-')) {
    return `https://unpkg.com/boxicons@${BOXICONS_VERSION}/svg/regular/${name}.svg`;
  }
  // Unicons drop the family prefix in their file names.
  return `https://unpkg.com/@iconscout/unicons@${UNICONS_VERSION}/svg/line/${name.slice(4)}.svg`;
};

async function collectSources(dir) {
  const found = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      found.push(...(await collectSources(full)));
    } else if (['.jsx', '.js'].includes(extname(entry.name))) {
      found.push(full);
    }
  }
  return found;
}

// Every icon class mentioned anywhere in the app, including the ones that only
// appear inside a ternary (the theme toggle's sun/moon), which is why this
// scans for the tokens rather than for whole className strings.
async function usedIcons() {
  const names = new Set();
  for (const file of await collectSources(SOURCE_DIR)) {
    const text = await readFile(file, 'utf8');
    for (const [name] of text.matchAll(/\b(?:bxl?s?-|uil-)[a-z0-9]+(?:-[a-z0-9]+)*/g)) {
      names.add(name);
    }
  }
  return [...names].sort();
}

// Inline SVG in a CSS url() only needs these escaped; leaving the rest as
// literal characters keeps the file readable and noticeably smaller than
// base64, which inflates by a third.
const dataUri = (svg) =>
  `data:image/svg+xml,${svg
    .replace(/\s+/g, ' ')
    .trim()
    .replaceAll('"', "'")
    .replaceAll('%', '%25')
    .replaceAll('#', '%23')
    .replaceAll('<', '%3C')
    .replaceAll('>', '%3E')}`;

async function fetchIcon(name) {
  const response = await fetch(sourceUrl(name));
  if (!response.ok) return null;
  const svg = await response.text();
  if (!svg.includes('<svg')) return null;
  // Force the glyph to paint solid so the mask covers the whole shape; the
  // colour comes from background-color on the element.
  return svg.replace(/fill="(?!none)[^"]*"/g, 'fill="#000"');
}

const HEADER = `/* Generated by scripts/generate-icon-css.mjs — do not edit by hand.
 *
 * Local replacements for the Boxicons and Unicons webfonts, covering only the
 * icons this site actually uses. Regenerate with \`npm run icons\`.
 *
 * Each icon is a mask over currentColor, so \`color\` tints it and \`font-size\`
 * scales it, exactly as the fonts behaved. */

.bx,
.uil {
  display: inline-block;
  width: 1em;
  height: 1em;
  background-color: currentColor;
  vertical-align: middle;
  flex-shrink: 0;
  -webkit-mask-repeat: no-repeat;
  mask-repeat: no-repeat;
  -webkit-mask-position: center;
  mask-position: center;
  -webkit-mask-size: 100% 100%;
  mask-size: 100% 100%;
}
`;

async function run() {
  const names = await usedIcons();
  const rules = [];
  const missing = [];

  for (const name of names) {
    const svg = await fetchIcon(name);
    if (!svg) {
      missing.push(name);
      continue;
    }
    const uri = dataUri(svg);
    rules.push(
      `.${name} {\n  -webkit-mask-image: url("${uri}");\n  mask-image: url("${uri}");\n}`
    );
  }

  await writeFile(OUTPUT, `${HEADER}\n${rules.join('\n\n')}\n`, 'utf8');

  console.log(`Icons: ${rules.length} written to src/assets/icons.css.`);
  if (missing.length > 0) {
    // Loud on purpose: a missing icon renders as an empty box, which is easy to
    // miss in review and impossible to miss here.
    console.error(`MISSING (no SVG found upstream): ${missing.join(', ')}`);
    process.exitCode = 1;
  }
}

await run();
